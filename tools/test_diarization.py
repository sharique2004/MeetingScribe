#!/usr/bin/env python3
"""Regression tests for the mic-only fallback — the thing that broke this week.

WHAT THIS GUARDS
----------------
When an online meeting's system (call-audio) track comes back empty, both sides
of the call were recorded on the microphone, so pipeline clusters the MIC like a
room mic instead of labelling all of it "You". Two independent decisions have to
be right, and both were wrong at some point this week:

  1. _system_track_lost()          — did the system track really record nothing?
     The defect: judging it by a RATIO (system speech ÷ mic speech) instead of an
     ABSOLUTE zero. Every real 1:1 call in the corpus has a system track that is
     quieter than the mic; a ratio gate fires on meetings whose call audio was
     captured perfectly and hands them to the fallback.

  2. _mic_holds_a_second_voice()   — was anybody else actually on that mic?
     The defect: using "the clustering returned more than one cluster" as the
     test. Solo mic tracks split into 2-3 clusters routinely, so under a
     cluster-count test the valve never closes and the user loses their "You"
     label on a meeting that was never broken.

TWO CORPORA
-----------
test/synthetic/   THE BASELINE. Committed, privacy-free, and generated by
                  tools/make_synthetic_fixtures.py from a fixed seed — no audio
                  and no real recording is involved. Every fixture ships a
                  labels.json stating the TRUE number of voices on each track,
                  which is the thing the private corpus cannot provide. This
                  corpus always runs, so the suite works on a clean clone.

test/fixtures/    OPTIONAL, deeper, LOCAL ONLY. Frozen caches of real meetings;
                  gitignored because the titles carry participants' names and
                  analysis.npz holds their ECAPA voice embeddings. It ships no
                  labels, but tools/eval_diarization.py carries a reviewed TRUTH
                  table for 21 of its 22 meetings, and the rows below are read
                  from it. When the corpus is absent every check simply runs on
                  synthetic alone and says so.

                  THIS FILE NAMES NONE OF THOSE MEETINGS. Every local fixture is
                  referred to by the stable pseudonym from
                  docs/DIARIZATION_AUDIT_ADDENDUM.md §0 (Call A..N, Demo, E2E,
                  Room P..W) — in the truth table, in the fixtures singled out by
                  hand, and in everything printed. The pseudonym -> directory map
                  is the de-anonymisation key, so it lives with the data it
                  describes in the gitignored test/fixtures/index.json and is
                  read at runtime; without it the local corpus is simply
                  unavailable, which is the normal state on a clean clone.

EXPECTATIONS COME FROM GROUND TRUTH, NOT FROM THE CODE
------------------------------------------------------
Every number this file asserts about the clustering is derived from how many
people were really on the track — never re-recorded from what the clustering
happens to output today. A table that is re-recorded whenever the fold rule
changes can only agree with the fold rule, which is the one thing it must be
able to disagree with. See the Row class and the table comment for the contract,
including how a case the code cannot currently get right is recorded without
turning the table back into a mirror.

Every check runs against every corpus that is present. Nothing here reads audio,
transcribes, downloads a model, or touches the network; recordings/ and
~/.meetingscribe/ are never opened, and every fixture is copied into a temp dir
before anything that writes runs.

    ~/.meetingscribe/venv/bin/python tools/test_diarization.py

Check functions are named check_* and all work is behind __main__, so a stray
`pytest tools/` collects and runs nothing.
"""

