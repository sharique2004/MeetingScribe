class Corpus:
    """One directory of frozen fixtures plus the ground truth about it.

    Fixtures are addressed by KEY. For the synthetic corpus a key is the
    fixture's own slug, which names nobody. For the local corpus a key is the
    pseudonym, and the key -> directory mapping is read from that corpus's own
    gitignored index (resolve() below) so this file never contains one.
    """

    def __init__(self, name, root, mic_rows, solo_mic, multi_mic,
                 quiet_system, min_online, ask_demo, description,
                 pseudonymous=False):
        self.name = name
        self.root = root
        self.mic_rows = mic_rows
        self.solo_mic = solo_mic
        self.multi_mic = multi_mic
        self.quiet_system = quiet_system
        self.min_online = min_online
        self.ask_demo = ask_demo
        self.description = description
        self.pseudonymous = pseudonymous
        self._slug_by_key = {}
        self._key_by_slug = {}
        self._resolve_problem = ""

    def __repr__(self):
        return f"<corpus {self.name}>"

    def resolve(self):
        """Load the key -> directory map. Returns "" or a reason it is absent.

        Only a pseudonymous corpus needs one: for the synthetic corpus the key
        IS the directory. tools/eval_diarization.py owns the reader, so the unit
        test and the eval harness cannot disagree about which meeting a label
        names.
        """
        if not self.pseudonymous:
            return ""
        self._slug_by_key, self._key_by_slug = {}, {}
        if eval_mod is None:
            self._resolve_problem = (
                "tools/eval_diarization.py could not be imported, so the "
                "pseudonym -> fixture map cannot be read")
            return self._resolve_problem
        mapping, why_not = eval_mod.load_label_map(self.root)
        if not mapping:
            self._resolve_problem = why_not
            return why_not
        self._slug_by_key = dict(mapping)
        self._key_by_slug = {v: k for k, v in mapping.items()}
        self._resolve_problem = ""
        return ""

    @property
    def resolve_problem(self):
        """Why this corpus cannot be addressed, or "" — set by resolve()."""
        return self._resolve_problem

    def slug_for(self, key):
        """The directory a key names. Unmapped keys pass through unchanged."""
        return self._slug_by_key.get(key, key)

    def key_for(self, slug):
        """The pseudonym a directory is known by. Unmapped ones pass through."""
        return self._key_by_slug.get(slug, slug)

    @property
    def present(self):
        if not (self.root.is_dir() and any(self.root.glob("*/meeting.json"))):
            return False
        return not self.resolve()

    def dirs(self):
        return sorted(p for p in self.root.iterdir()
                      if p.is_dir() and (p / "meeting.json").exists())

    def keys(self):
        """Every fixture present on disk, named the way this file names it."""
        return sorted(self.key_for(d.name) for d in self.dirs())


