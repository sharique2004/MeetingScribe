def fixture_dir(corpus, key):
    """The directory a KEY names — a pseudonym on the local corpus, a slug on
    the synthetic one. A directory name passed straight in still resolves, so
    the sibling suites that name synthetic fixtures directly keep working."""
    d = corpus.root / corpus.slug_for(key)
    if not d.is_dir():
        raise SystemExit(f"missing fixture {key} under {corpus.root}")
    return d


def load_transcripts(corpus, slug):
    """Deep copy of a fixture's cached transcripts — callers mutate them."""
    path = fixture_dir(corpus, slug) / "analysis.json"
    return copy.deepcopy(json.loads(path.read_text(encoding="utf-8"))["transcripts"])


def load_meta(corpus, slug):
    return json.loads(
        (fixture_dir(corpus, slug) / "meeting.json").read_text(encoding="utf-8"))


def load_labels(corpus, slug):
    """Ground truth, or None for a corpus that has none (the local one)."""
    path = fixture_dir(corpus, slug) / "labels.json"
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def load_precomputed(corpus, slug):
    """{track: (windows, embeddings)} straight from the frozen npz."""
    out = {}
    npz_path = fixture_dir(corpus, slug) / "analysis.npz"
    if not npz_path.exists():
        return out
    with np.load(npz_path) as npz:
        for key in npz.files:
            if not key.endswith("_embeddings"):
                continue
            track = key[: -len("_embeddings")]
            wkey = f"{track}_windows"
            if wkey in npz.files:
                out[track] = (np.array(npz[wkey]), np.array(npz[key]))
    return out


def has_mic_embeddings(corpus, slug):
    """True when the fixture carries a cached mic track, without loading it."""
    npz_path = fixture_dir(corpus, slug) / "analysis.npz"
    if not npz_path.exists():
        return False
    with np.load(npz_path) as npz:
        return "mic_embeddings" in npz.files and "mic_windows" in npz.files


def mic_state(corpus, slug):
    """The {"windows", "embeddings"} dict _mic_holds_a_second_voice expects."""
    pre = load_precomputed(corpus, slug)
    if "mic" not in pre:
        raise SystemExit(f"fixture {slug} has no cached mic embeddings")
    windows, embeddings = pre["mic"]
    return {
        "windows": [tuple(w) for w in np.asarray(windows).tolist()],
        "embeddings": np.asarray(embeddings, dtype=np.float64),
    }


# Clustering Room W's 4594-window track is the slowest thing in this file
# and three checks want the same labels, so each (fixture, folded?) pair is
# computed once. Deterministic input, deterministic clustering, so caching
# changes nothing but the runtime.
_LABEL_CACHE = {}


def mic_labels(corpus, slug, state=None, folded=True):
    """Per-window cluster labels for a mic track.

    folded=True is the auto path the app runs: cluster() is handed durations, so
    _fold_weak_clusters gets to repair same-voice splits. It is the identical
    call pipeline._mic_holds_a_second_voice makes internally.

    folded=False passes no durations, which skips the fold entirely. That is the
    RAW clustering — what the threshold and the k-ceiling produce before any
    repair — and it is how the checks below can talk about phantom over-splits
    without depending on how aggressive today's fold rule happens to be.
    """
    key = (corpus.name, slug, folded)
    if key not in _LABEL_CACHE:
        state = state or mic_state(corpus, slug)
        durations = ([w[1] - w[0] for w in state["windows"]] if folded else None)
        _LABEL_CACHE[key] = list(pipeline.diarization.cluster(
            state["embeddings"], n_speakers=None, threshold=THRESHOLD,
            durations=durations,
        ))
    return _LABEL_CACHE[key]


def cluster_purity(labels, true_voices):
    """Share of windows sitting in a cluster their own voice dominates.

    1.0 means no cluster mixes two real people. It is the half of correctness a
    cluster COUNT cannot see: three voices split into three clusters that each
    hold a bit of everyone scores 3 == 3 on the count and 0.33 here.
    """
    total = 0
    for lab in set(labels):
        seen = Counter(v for l, v in zip(labels, true_voices) if l == lab)
        total += max(seen.values())
    return total / float(len(true_voices))


def _num(x):
    """Format a measurement that may legitimately be absent (one cluster)."""
    return "  n/a" if x is None else f"{x:.3f}"


@contextlib.contextmanager
def recluster_workdir(corpus, slug):
    """A temp copy of a fixture, rewritten as an online call with no call audio.

    Yields the directory. recluster_meeting() writes meeting.json (and possibly
    analysis.*) into it, so it must never be the fixture itself.
    """
    with tempfile.TemporaryDirectory(prefix="ms-recluster-test-") as tmp:
        work = Path(tmp) / slug
        shutil.copytree(fixture_dir(corpus, slug), work)

        meta_path = work / "meeting.json"
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        meta["mode"] = "online"
        for key in ("diarization_mode", "speaker_count_source",
                    "speaker_count_basis"):
            meta.pop(key, None)
        meta_path.write_text(json.dumps(meta), encoding="utf-8")

        analysis_path = work / "analysis.json"
        analysis = json.loads(analysis_path.read_text(encoding="utf-8"))
        analysis["transcripts"]["system"] = []  # the silent call-audio track
        analysis_path.write_text(json.dumps(analysis), encoding="utf-8")

        yield work


def label_as_online_mic_only(corpus, slug, expected=None, meta_overrides=None):
    """Run pipeline's labelling step over a fixture presented as a mic-only call.

    Returns (meta, warnings). The fixture is copied to a temp dir first, so the
    corpus is never written to even if the pipeline changes to write.
    """
    with tempfile.TemporaryDirectory(prefix="ms-diar-test-") as tmp:
        work = Path(tmp) / slug
        shutil.copytree(fixture_dir(corpus, slug), work)

        meta = load_meta(corpus, slug)
        meta["mode"] = "online"
        meta.pop("diarization_mode", None)
        meta.pop("speaker_count_source", None)
        meta.pop("speaker_count_basis", None)
        meta.update(meta_overrides or {})

        transcripts = load_transcripts(corpus, slug)
        transcripts["system"] = []  # the silent call-audio track

        warnings = pipeline._label_and_assemble(
            work, meta, transcripts, pipeline.load_config(), expected,
            lambda msg: None, precomputed=load_precomputed(corpus, slug),
            collect={},
        )
    return meta, warnings


