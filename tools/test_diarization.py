# ---------------------------------------------------------------------------
# WHAT A ROW SAYS, AND WHY IT IS NOT A RECORDING OF THE CODE
#
# The previous version of this table stored the auto cluster count and the
# detector's verdict as MEASURED NUMBERS, re-recorded whenever the clustering
# changed. That is a mirror, not a test: after the second re-recording it can
# only ever agree with whatever _fold_weak_clusters does today, so it cannot
# catch the very defect it exists for (a real participant folded away, or a
# phantom promoted to a speaker).
#
# So a row states GROUND TRUTH — how many people are really on that mic track —
# and the expectations are derived from it:
#
#     expected cluster count  ==  truth
#     expected verdict        ==  (truth > 1)
#
# Ground truth is never written here by hand. Synthetic rows come from the
# fixture's own labels.json (generated with the voices, so it is construction
# truth, not opinion); local rows come from the reviewed TRUTH table in
# tools/eval_diarization.py. check_the_table_is_grounded_in_truth re-reads both
# every run, so a row that quietly acquires a comfortable "truth" fails.
#
# A row may also record ONE documented miss — a second accepted answer for a
# case the code is known to get wrong and cannot currently get right. Truth and
# the recorded miss both pass; ANYTHING ELSE FAILS. That is what keeps the table
# honest in both directions:
#   * a change that moves a row off truth (or off its recorded miss) onto some
#     third answer is a regression and goes red;
#   * a change that moves a recorded miss ONTO the truth is reported as
#     IMPROVED, stays green, and the miss line can be deleted.
#
# measured 2026-07-25, threshold 0.6, detector gates ratio>=0.25, frag<=0.30
#
#   fixture                  truth  auto  ratio   frag   verdict
#   solo-one-voice               1     1    n/a    n/a   you      correct
#   same-voice-drift             1     1    n/a    n/a   you      correct
#   same-voice-split             1     1    n/a    n/a   you      correct
#   same-voice-big-split         1     1    n/a    n/a   you      correct
#   ask-demo-call                1     1    n/a    n/a   you      correct
#   two-long-turns               2     2  1.000  0.100   second   correct
#   two-medium-turns             2     2  1.000  0.250   second   correct
#   two-rapid-alternation        2     2  1.000  0.333   you      *** MISS ***
#   two-backchannel              2     1    n/a    n/a   you      *** MISS ***
#   three-voices                 3     3  1.000  0.167   second   correct
#   four-voices                  4     4  1.000  0.200   second   correct
#
# THE TWO MISSES ARE THE POINT OF THIS CORPUS, and they are different failures:
#
#   two-rapid-alternation — the CLUSTERING is right (2 clusters, one per voice,
#     every window correctly assigned) and the DETECTOR's gate is wrong.
#     Fragmentation is essentially 1/(turn_length - 1) for an alternating
#     conversation, so pipeline.MIC_ONLY_MAX_FRAGMENTATION = 0.30 is really a
#     rule about how fast people take turns, not about who is speaking:
#
#       genuine 2 speakers, 11 s turns -> 0.100   same voice, scattered -> 0.778
#       genuine 2 speakers,  5 s turns -> 0.250   same voice, large lobe -> 0.714
#       genuine 2 speakers,  3 s turns -> 0.333
#
#     The bands OVERLAP; docs/COUNT_ESTIMATION_DESIGN.md read them as separable
#     from long-turn meetings only, and the separation closes below roughly a
#     five-second turn.
#
#   two-backchannel — the CLUSTERING is wrong: _fold_weak_clusters folds the
#     genuine second person away, so the detector never gets a runner-up to
#     judge. diarization.py names this same fixture as its one measured loss and
#     says separating it needs a speaker-verification score, not another
#     threshold. If the absolute size ceiling being added to the fold rule
#     rescues it, this row goes IMPROVED and its miss line comes out.
# ---------------------------------------------------------------------------


class Row:
    """One cached mic track: what is TRUE about it, plus any documented miss.

    truth          voices really on that track, or None when it cannot be
                   established from the fixture at all.
    at_least       lower bound, used ONLY where truth is None: a weaker claim
                   that is still evidence, so an unknowable row asserts
                   something instead of asserting nothing.
    miss_clusters  a second accepted cluster count (see the table comment).
    miss_verdict   a second accepted _mic_holds_a_second_voice verdict.
    why            what this row is in the corpus to prove.
    """

    def __init__(self, truth=None, why="", at_least=None,
                 miss_clusters=None, miss_verdict=None):
        if truth is None and at_least is None:
            raise ValueError("a row with no truth needs an at_least bound")
        self.truth = truth
        self.at_least = at_least
        self.miss_clusters = miss_clusters
        self.miss_verdict = miss_verdict
        self.why = why

    @property
    def wants_second_voice(self):
        """What ground truth says the mic-only detector should answer."""
        return (self.truth if self.truth is not None else self.at_least) > 1

    def rate_clusters(self, n):
        """'ok' (matches truth), 'miss' (the documented one), or 'bad'."""
        if self.truth is None:
            return "ok" if n >= self.at_least else "bad"
        if n == self.truth:
            return "ok"
        if self.miss_clusters is not None and n == self.miss_clusters:
            return "miss"
        return "bad"

    def rate_verdict(self, got):
        if got == self.wants_second_voice:
            return "ok"
        if self.miss_verdict is not None and got == self.miss_verdict:
            return "miss"
        return "bad"


