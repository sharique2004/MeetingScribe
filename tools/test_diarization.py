        "SKIPPED the optional local corpus. It is gitignored on purpose (real "
        "participants' voice embeddings, and directory names that are real "
        "meeting titles), so this is the normal state on a clean clone, and the "
        "committed synthetic corpus covers every check below.\n"
        f"  reason: {reason}"
