# ---------------------------------------------------------------------------
# Tunables that --set may override on the diarization module. Whitelisted so a
# typo cannot silently do nothing.
#
# THE WHITELIST MUST REACH EVERY CONSTANT THAT DECIDES THE COUNT, or the
# documented threshold-sweep workflow silently sweeps nothing. That has already
# happened once: the D2 fold rule moved the decision into FOLD_MAX_FRAGMENTATION
# and FOLD_MAX_DURATION_RATIO while this list still held only the pre-D2 names,
# so --set could not touch the two constants that now set every speaker count.
# audit_tunables() below re-checks that automatically on every run rather than
# trusting this comment to stay true.
# ---------------------------------------------------------------------------
TUNABLES = {
    # window geometry — sweepable, but see blind spot (b): changing these
    # invalidates every cache, so a sweep over them is not measurable here.
    "WINDOW_S": float,
    "HOP_S": float,
    "MIN_WINDOW_S": float,
    # the count-deciding constants, all read by cluster()/_fold_weak_clusters
    "MAX_AUTO_SPEAKERS": int,       # ceiling on the refit
    "MIN_CLUSTER_S": float,         # absolute small-cluster floor
    "FOLD_KEEP_ABOVE_S": float,     # absolute never-fold-above ceiling
    "FOLD_MAX_FRAGMENTATION": float,  # scatter gate  (D2)
    "FOLD_MAX_DURATION_RATIO": float,  # size gate vs the leading voice  (D2)
    "THRESHOLD": float,  # not a module attr; passed to cluster()
}

# Module-level names in diarization.py that decide the auto speaker count. Any
# name matching one of these prefixes must be in TUNABLES; audit_tunables()
# reports the ones that are not, so a constant added to the fold rule after this
# file was written still shows up instead of being silently unsweepable.
COUNT_CONSTANT_PREFIXES = ("FOLD_", "MIN_CLUSTER", "MAX_AUTO", "MERGE_", "CLUSTER_")


def audit_tunables():
    """Return names diarization.py exposes that TUNABLES cannot reach.

    Detects, rather than assumes, that the sweep tool covers the fold rule.
    """
    missing = []
    for name in sorted(dir(diarization)):
        if name.startswith("_") or name in TUNABLES:
            continue
        if not any(name.startswith(p) for p in COUNT_CONSTANT_PREFIXES):
            continue
        if isinstance(getattr(diarization, name), (int, float)) and not isinstance(
            getattr(diarization, name), bool
        ):
            missing.append(name)
    return missing


def constant_drift():
    """Count-deciding constants whose live value differs from BASELINE_CONSTANTS.

    Returns [(name, recorded, live)]. A live value of MISSING means the constant
    was removed from diarization.py since the baseline was recorded.
    """
    out = []
    for name, recorded in sorted(BASELINE_CONSTANTS.items()):
        live = getattr(diarization, name, "MISSING")
        if live != recorded:
            out.append((name, recorded, live))
    return out


