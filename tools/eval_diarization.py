MISSING_INDEX_NOTE = (
    "%s is missing, so the pseudonym -> fixture mapping this harness needs is "
    "not\n      available. That mapping is the de-anonymisation key for the real "
    "corpus and is\n      deliberately kept out of git, so a clean clone never "
    "has it: the real corpus is\n      simply unavailable here and everything "
    "below runs on test/synthetic/ alone."
)


def load_label_map(fixtures_dir):
    """Read {pseudonym: directory name} out of the gitignored corpus index.

    Returns ({}, reason) when the corpus or its index is absent or unreadable —
    never raises, because "no mapping" is a supported state (clean clone), not
    an error. The reason is a sentence fit to print.
    """
    SLUG_BY_LABEL.clear()
    LABEL_BY_SLUG.clear()
    fixtures_dir = Path(fixtures_dir)
    if not fixtures_dir.is_dir():
        return {}, ("no real corpus at %s — it is gitignored (real voices, real "
                    "names), so this is the normal state on a clean clone."
                    % fixtures_dir)
    path = fixtures_dir / FIXTURE_INDEX
    if not path.exists():
        return {}, MISSING_INDEX_NOTE % path
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return {}, "%s is unreadable (%s) — the real corpus cannot be addressed." % (
            path, exc)
    if not isinstance(data, dict):
        return {}, "%s is not a JSON object — expected {\"labels\": {...}}." % path
    labels = data.get("labels")
    if labels is None and all(k in LABEL_KINDS for k in data):
        labels = data  # the accepted flat form
    if not isinstance(labels, dict) or not labels:
        return {}, (
            "%s carries no \"labels\" map, so no pseudonym can be resolved to a "
            "fixture.\n      Expected {\"labels\": {\"Call A\": \"<directory "
            "name>\", ...}}." % path
        )
    for label, slug in labels.items():
        if not isinstance(slug, str) or not slug:
            continue
        SLUG_BY_LABEL[label] = slug
        LABEL_BY_SLUG[slug] = label
    return dict(SLUG_BY_LABEL), ""


# Synthetic slugs are safe to print: tools/make_synthetic_fixtures.py refuses to
# emit any real name, so there is nothing to pseudonymise. The trailing
# -YYYYMMDD-HHMMSS is stripped so the label says what the fixture tests.
SYNTHETIC_SLUG_RE = re.compile(r"^synthetic-(.*)-\d{8}-\d{6}$")


def is_synthetic(key):
    return bool(SYNTHETIC_SLUG_RE.match(key))


def key_of(slug):
    """The key a fixture directory is known by everywhere in this harness.

    A real fixture is keyed by its pseudonym; a synthetic one by its own slug,
    which names nobody. A real fixture the index does not map falls back to its
    directory name so it still gets a row — reported as unlabelled, and loudly
    uncovered by --check until someone gives it a label.
    """
    return LABEL_BY_SLUG.get(slug, slug)


def label_of(key):
    """Stable pseudonym for a fixture. Unknown fixtures get a marked stand-in."""
    if key in LABEL_KINDS:
        return key
    m = SYNTHETIC_SLUG_RE.match(key)
    if m:
        return "syn/" + m.group(1)
    return "?" + key[:8]


def kind_of(key):
    if key in LABEL_KINDS:
        return LABEL_KINDS[key]
    if is_synthetic(key):
        return ""  # the label already says what it is
    return "unlabelled fixture"


# Truth for the synthetic corpus, filled in by load_fixtures() from each
# fixture's labels.json. Kept in its own dict, never merged into TRUTH: TRUTH is
# hand-written and reviewable, this is generated alongside the embeddings, and a
# reader must be able to tell which is which.
SYNTHETIC_TRUTH = {}


def truth_of(key):
    """Return (count, tier, note). Missing keys are unknown, never silently 0."""
    if key in TRUTH:
        return TRUTH[key]
    if key in SYNTHETIC_TRUTH:
        return SYNTHETIC_TRUTH[key]
    return (None, "unknown", "no truth entry in this harness")


def scored_truth(key):
    """The count the better/worse classifier may use, or None."""
    count, tier, _ = truth_of(key)
    return count if tier in ("known", "inferred") else None

