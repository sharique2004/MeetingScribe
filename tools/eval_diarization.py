MARKER_KEY = "embed_version"  # what pipeline._save_analysis_state() writes
# Only tried in case a cache was ever written under a different name; none of
# the shipped writers use these.
MARKER_FALLBACK_KEYS = ("version", "cache_version", "schema_version", "_version")


def npz_version_marker(npz):
    """Return the embedding-version marker stored in analysis.npz, or None.

    None means the entry is absent, which is NOT the same as "unknown" — see
    effective_embed_version().
    """
    for key in (MARKER_KEY,) + MARKER_FALLBACK_KEYS:
        if key in npz.files:
            return str(npz[key])
    return None


def effective_embed_version(marker):
    """The version a cache is actually treated as, mirroring pipeline's rule.

    A missing marker reads as 1: caches predate the marker and were produced by
    EMBED_VERSION 1 behaviour, so pipeline.recluster_meeting() reuses them
    rather than needlessly re-embedding every existing meeting. Returns None
    only for a marker that is present but not an integer.
    """
    if marker is None:
        return 1
    try:
        return int(marker)
    except (TypeError, ValueError):
        return None


def load_synthetic_truth(d, track):
    """Truth for one synthetic fixture, read from the labels.json shipped with it.

    Returns (count, tier, note) or None when the fixture carries no labels for
    the track being clustered.

    The count is the number of DISTINCT TRUE VOICES ON THE CLUSTERED TRACK, not
    the fixture's overall true_speaker_count. They differ: the online
    synthetic-ask-demo-call has 3 voices in the meeting but only 2 of them on the
    system track, and 2 is what a system-track cluster count can possibly be
    right about. This mirrors the per-track rule the real TRUTH table follows.
    """
    lp = d / "labels.json"
    if not lp.exists():
        return None
    try:
        lab = json.loads(lp.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    tr = (lab.get("tracks") or {}).get(track) or {}
    voices = tr.get("true_voices")
    if not voices:
        return None
    return (
        len(voices),
        "known",
        "constructed: labels.json lists %d true voice(s) on the %s track"
        % (len(voices), track),
    )


def load_fixtures(fixtures_dir, corpus="real", required=False):
    """Yield one record per frozen fixture, newest-cache-format agnostic.

    corpus is "real" (test/fixtures, gitignored, hand-written truth) or
    "synthetic" (test/synthetic, committed, truth generated with the fixture).
    Synthetic fixtures register their truth in SYNTHETIC_TRUTH as they load.
    Each record carries both its "key" (the pseudonym everything else in this
    harness is keyed by) and its "slug" (the directory on disk, which is only
    ever printed under --show-titles).
    A missing directory is fatal only when `required`; BOTH corpora are optional
    — the real one is gitignored and absent on a clean clone, the synthetic one
    is skipped by --no-synthetic — so the caller reports and carries on.
    """
    out = []
    if not fixtures_dir.is_dir():
        if required:
            raise SystemExit(f"no fixtures at {fixtures_dir} — freeze them first")
        return out
    for d in sorted(p for p in fixtures_dir.iterdir() if p.is_dir()):
        npz_path = d / "analysis.npz"
        meta_path = d / "meeting.json"
        if not npz_path.exists() or not meta_path.exists():
            continue
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        with np.load(npz_path, allow_pickle=False) as npz:
            marker = npz_version_marker(npz)
            tracks = {}
            for key in ("mic", "system"):
                wk, ek = f"{key}_windows", f"{key}_embeddings"
                if wk in npz.files and ek in npz.files:
                    tracks[key] = (
                        np.asarray(npz[wk], dtype=np.float64),
                        np.asarray(npz[ek], dtype=np.float64),
                    )
        if not tracks:
            continue
        # The track diarization actually clusters: system for online meetings,
        # mic for in-person. Fall back to whichever track the cache holds.
        mode = meta.get("mode", "online")
        preferred = "system" if mode == "online" else "mic"
        track = preferred if preferred in tracks else next(iter(tracks))
        if corpus == "synthetic":
            t = load_synthetic_truth(d, track)
            if t is not None:
                SYNTHETIC_TRUTH[d.name] = t
        out.append(
            {
                "key": d.name if corpus == "synthetic" else key_of(d.name),
                "slug": d.name,
                "dir": d,
                "corpus": corpus,
                "mode": mode,
                "track": track,
                "cached_tracks": sorted(tracks),
                "windows": tracks[track][0],
                "embeddings": tracks[track][1],
                "expected_speakers": meta.get("expected_speakers") or None,
                "shipped_speakers": meta.get("speakers") or {},
                "warnings": meta.get("warnings") or [],
                "version_marker": marker,
            }
        )
    return out


CORPUS_ORDER = ("real", "synthetic")
CORPUS_DIR = {"real": "test/fixtures/", "synthetic": "test/synthetic/"}
CORPUS_BLURB = {
    "real": "real cached meetings — truth mostly INFERRED, gitignored, local only",
    "synthetic": "generated fixtures — truth CONSTRUCTED per window, committed",
}


def of_corpus(fixtures, corpus):
    return [fx for fx in fixtures if fx.get("corpus", "real") == corpus]


