#!/usr/bin/env python3
"""Offline evaluation harness for MeetingScribe speaker diarization.

Runs diarization.cluster() over FROZEN CACHED EMBEDDINGS from two corpora and
reports, as the headline, HOW OFTEN THE AUTOMATIC SPEAKER COUNT IS RIGHT:

  test/fixtures/   REAL corpus. analysis.npz + analysis.json + meeting.json
                   copied out of recordings/ (gitignored, unrecoverable). Real
                   ECAPA embeddings of real people; gitignored, local-only.
                   Truth is mostly INFERRED — see the TRUTH table's tiers.
                   ADDRESSED ONLY BY PSEUDONYM: this file is committed, so it
                   holds no meeting title or directory name anywhere. The
                   pseudonym -> directory map lives in that corpus's own
                   gitignored test/fixtures/index.json and is read at runtime.
                   Without it the real corpus is unavailable (the normal state
                   on a clean clone) and every run below is synthetic-only,
                   which the report states in place of a real-corpus line.
  test/synthetic/  SYNTHETIC corpus, committed and privacy-free, generated by
                   tools/make_synthetic_fixtures.py. Each fixture ships a
                   labels.json with per-window true voices, so its speaker count
                   is CONSTRUCTED, not inferred — the only ground truth here that
                   is not a reading of the evidence. Its embeddings are generated,
                   so it measures cluster() arithmetic, NOT voice separability.

Nothing is transcribed, no audio is read, no recording is touched — the harness
is read-only with respect to recordings/.

    python tools/eval_diarization.py                 # accuracy + baseline report
    python tools/eval_diarization.py --check         # gate against BEHAVIOUR_BASELINE
    python tools/eval_diarization.py --save-baseline out.json   # plain runs only
    python tools/eval_diarization.py --baseline out.json --set MIN_CLUSTER_S=15
    python tools/eval_diarization.py --set FOLD_MAX_FRAGMENTATION=0.15   # sweep
    python tools/eval_diarization.py --baseline out.json --variant-module my_cluster.py
    python tools/eval_diarization.py --no-synthetic  # real corpus only

--check GATES EVERY FIXTURE ON DISK, IN BOTH CORPORA. A fixture with no baseline
entry is reported as UNCOVERED and fails, because the alternative — skipping it
silently and then printing "reproduced" — turns partial coverage into a claim of
full coverage.

TWO SEPARATE CONCEPTS, AND THE HARNESS REFUSES TO BLUR THEM:

  BEHAVIOUR_BASELINE  is a CHANGE-DETECTOR. It pins the count each fixture
                      produces *today*. Reproducing it proves only that
                      clustering behaviour did not move. It is re-recorded
                      whenever the rule deliberately changes, and re-recording it
                      asserts NOTHING about correctness.
  TRUTH               is what CORRECTNESS is measured against. It is written by
                      hand (real corpus) or generated with the fixture (synthetic
                      corpus) and is NEVER updated to match the code.

Concretely: an entry may be baselined at a number that TRUTH says is wrong. The
report lists every such entry out loud under "PINNED BUT WRONG" so a
re-baseline cannot quietly become "whatever the code does is correct".

--save-baseline writes a {pseudonym: result} map and only works on a plain run;
an A/B run holds two result maps and the write is refused rather than silently
producing a file --baseline and --check cannot read. Snapshots are keyed by
pseudonym like everything else, so a saved baseline is safe to paste.

THREE BLIND SPOTS — these limit every conclusion drawn from this harness. The
harness prints them at the top of every run, COMPUTED FROM THE REAL FIXTURE SET
IT JUST LOADED (see blind_spots()) rather than quoted from a hand-written
constant, because the corpus grows and a stale hand-written claim is worse than
none:

  (a) among the real caches, none holds both tracks, so "You vs remote"
      separation cannot be A/B tested from them. Online meetings cache the system
      track only (no local voice at all); in-person meetings cache the mic track
      only (every voice, the local user included). The exact split is recomputed
      each run.
  (b) Cache-based A/B cannot cover changes to window geometry, VAD gating, or
      window-length rules — any such change invalidates all caches.
  (c) The synthetic corpus has the ground truth the real one lacks, but its
      embedding VECTORS are drawn from a seeded generator, not from ECAPA over
      real audio. It can prove that cluster() separates well-separated vectors
      and folds scattered lobes; it cannot prove that two real human voices land
      far enough apart to be separated at all. A synthetic pass is never
      evidence about real audio, which is why the accuracy report keeps the two
      corpora on separate lines and never sums them.

THE CACHE HAS A VERSION MARKER, AND IT COVERS LESS THAN IT LOOKS LIKE.
analysis.npz stores two arrays per track (``<track>_windows`` float64 (N,2) and
``<track>_embeddings`` float32 (N,192)) plus one scalar entry,
``embed_version``, written by pipeline._save_analysis_state() from
diarization.EMBED_VERSION. pipeline.recluster_meeting() reads it and refuses to
reuse a cache whose version differs from the running code, re-embedding
instead. A cache with NO ``embed_version`` is read as version 1 — not as
"unknown" — because every cache written before the marker existed came from
EMBED_VERSION 1 behaviour. This harness reports the same reading, so the frozen
fixtures (all captured pre-marker) show version 1 (implicit), which is current
while EMBED_VERSION is still 1.

WHAT THE MARKER DOES NOT GUARD:

  * It is a hand-maintained stamp, not a fingerprint. If build_windows(),
    WINDOW_S/HOP_S/MIN_WINDOW_S, the VAD, or the ECAPA checkpoint changes and
    nobody bumps diarization.EMBED_VERSION, stale caches still read as current
    and this harness keeps reporting numbers from embeddings the code would
    never produce.
  * It says nothing about transcript/cache agreement. _save_analysis_state()
    writes analysis.npz only when it has embeddings to write (``if arrays:``),
    so a Reprocess whose embedding set comes out empty rewrites analysis.json
    and leaves the OLD analysis.npz untouched — a new transcript sitting beside
    a stale cache, with the version unchanged and therefore no signal that the
    two disagree.

Treat cache-based results as valid only for changes downstream of embedding,
i.e. inside cluster() and its helpers.
"""

