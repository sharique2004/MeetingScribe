TIER_MARK = {"known": "K", "inferred": "i", "unknown": "?"}


def pinned_but_wrong(fixtures):
    """Baseline entries that TRUTH says are the wrong number.

    Printed on every run. The gate still pins them — its job is to catch drift —
    but a re-baseline must never be able to launder a wrong answer into "correct
    because the baseline says so", so these are named out loud each time.
    """
    out = []
    for fx in fixtures:
        key = fx["key"]
        base = BASELINE.get(key)
        t = scored_truth(key)
        if base is not None and t is not None and base != t:
            out.append((key, base, t))
    return out


def print_baseline_table(fixtures, res, show_titles=False):
    """Print the per-fixture table. Returns (mismatches, uncovered)."""
    hdr = "%-47s %-9s %-4s %5s %6s %5s %5s %5s %5s %5s %4s" % (
        "meeting (real title only with --show-titles)" if show_titles else "meeting",
        "mode", "trk", "wins", "expect", "ship", "auto",
        "base", "was", "truth", "err"
    )
    print(hdr)
    print("-" * len(hdr))
    mismatches, uncovered = [], []
    for fx in fixtures:
        key = fx["key"]
        r = res[key]
        shipped = len(fx["shipped_speakers"])
        # "you" is assigned by track, not by clustering — subtract it so the
        # shipped number is comparable to a cluster count.
        shipped_clusters = shipped - (1 if "you" in fx["shipped_speakers"] else 0)
        base = BASELINE.get(key)
        prev = PREVIOUS_GENERATION.get(key)
        was = "-" if prev is None else ("=" if prev == base else str(prev))
        count, tier, _ = truth_of(key)
        truth_cell = "%s%s" % (count if count is not None else "-", TIER_MARK[tier])
        err = "" if count is None else "%+d" % (r["auto"] - count)
        flag = ""
        if base is None:
            flag = "  <-- NO BASELINE (unvalidated)"
            uncovered.append(key)
        elif base != r["auto"]:
            flag = "  <-- DISCREPANCY vs baseline"
            mismatches.append((key, base, r["auto"]))
        elif count is not None and base != count:
            flag = "  <-- pinned, but TRUTH says %d" % count
        print(
            "%-47s %-9s %-4s %5d %6s %5s %5d %5s %5s %5s %4s%s"
            % (
                row_name(key, show_titles),
                fx["mode"],
                fx["track"][:3],
                r["windows"],
                fx["expected_speakers"] if fx["expected_speakers"] else "-",
                "%d(%d)" % (shipped_clusters, shipped),
                r["auto"],
                base if base is not None else "-",
                was,
                truth_cell,
                err,
                flag,
            )
        )
    print()
    print("columns: meeting=stable pseudonym (--show-titles for the real slug);")
    print("              syn/* rows are the committed synthetic corpus and carry no names")
    print("         wins=cached ECAPA windows | expect=meeting.json expected_speakers")
    print("         ship=clusters in shipped speaker map (total incl. 'you' in parens)")
    print("         auto=cluster(n_speakers=None) now | base=gated baseline (gen %s)"
          % BASELINE_DATE)
    print("         was=the same fixture's entry in the PREVIOUS baseline generation")
    print("             ('=' unchanged, '-' no earlier entry) — what the rule change moved")
    print("         truth=voices on the CLUSTERED track, K=known/constructed i=inferred ?=unknown")
    print("              system track counts remote voices only (you are not in it);")
    print("              mic track counts every voice on the mic, you included.")
    print("         err=auto minus truth; blank where truth is unknown")
    forced = [fx for fx in fixtures if fx["expected_speakers"]]
    print()
    print(
        "WARNING: %d of %d fixtures shipped with expected_speakers FORCED from the "
        "calendar. Their 'ship' column is worthless as a quality baseline — only the "
        "'auto' column measures the clustering." % (len(forced), len(fixtures))
    )
    for corpus in CORPUS_ORDER:
        sub = of_corpus(fixtures, corpus)
        if not sub:
            continue
        a = accuracy_of(sub, res)
        print("ACCURACY vs truth (%s): %d of %d truth-backed fixtures correct; %d wrong."
              % (corpus, len(a["hits"]), len(a["scorable"]), len(a["misses"])))
    print("         The baseline pins current behaviour; it does not claim current")
    print("         behaviour is correct.")
    return mismatches, uncovered


def print_ab_table(fixtures, base, var, show_titles=False):
    hdr = "%-47s %5s %6s %6s %8s" % ("meeting", "wins", "A auto", "B auto", "delta")
    print(hdr)
    print("-" * len(hdr))
    changed, worse, better = [], [], []
    for fx in fixtures:
        key = fx["key"]
        a, b = base[key]["auto"], var[key]["auto"]
        d = b - a
        truth = scored_truth(key)
        mark = ""
        if d:
            changed.append(key)
            if truth is not None:
                if abs(b - truth) < abs(a - truth):
                    better.append(key)
                    mark = "  better"
                elif abs(b - truth) > abs(a - truth):
                    worse.append(key)
                    mark = "  WORSE"
                else:
                    mark = "  neutral"
            else:
                mark = "  changed (no truth)"
        print(
            "%-47s %5d %6d %6d %8s%s"
            % (row_name(key, show_titles), base[key]["windows"], a, b,
               "%+d" % d if d else "0", mark)
        )
    print()
    scorable = sum(1 for fx in fixtures if scored_truth(fx["key"]) is not None)
    print(
        "A/B summary: %d/%d meetings changed | better: %d | WORSE: %d | "
        "golden demo: A=%d B=%d"
        % (
            len(changed), len(fixtures), len(better), len(worse),
            base.get(GOLDEN_KEY, {}).get("auto", -1),
            var.get(GOLDEN_KEY, {}).get("auto", -1),
        )
    )
    print(
        "  better/WORSE are scored against TRUTH, available for %d/%d fixtures "
        "(%d known, %d\n  inferred). Changes on the other %d are reported as "
        "\"changed (no truth)\" and score neither way."
        % (
            scorable, len(fixtures),
            sum(1 for fx in fixtures if truth_of(fx["key"])[1] == "known"),
            sum(1 for fx in fixtures if truth_of(fx["key"])[1] == "inferred"),
            len(fixtures) - scorable,
        )
    )
    return changed, better, worse


def check_golden(fixtures, res):
    """Protect the golden regression value. Returns list of failure strings."""
    fails = []
    fx = next((f for f in fixtures if f["key"] == GOLDEN_KEY), None)
    if fx is None:
        return ["golden fixture %s is missing" % GOLDEN_KEY]
    if len(fx["windows"]) != GOLDEN_WINDOWS:
        fails.append(
            "golden: %d ECAPA windows, expected %d" % (len(fx["windows"]), GOLDEN_WINDOWS)
        )
    if fx["shipped_speakers"] != {"you": "You", "s1": "Speaker 1", "s2": "Speaker 2"}:
        fails.append("golden: shipped speaker map is %s" % fx["shipped_speakers"])
    if fx["warnings"]:
        fails.append("golden: %d warnings, expected 0" % len(fx["warnings"]))
    got = res[GOLDEN_KEY]["auto"]
    if got != GOLDEN_AUTO_CLUSTERS:
        fails.append("golden: auto clusters %d, expected %d" % (got, GOLDEN_AUTO_CLUSTERS))
    return fails


