def _durations(windows):
    return [float(w[1]) - float(w[0]) for w in windows]


def run_cluster(fx, cluster_fn, n_speakers, threshold):
    labels = cluster_fn(
        fx["embeddings"],
        n_speakers=n_speakers,
        threshold=threshold,
        durations=_durations(fx["windows"]),
    )
    return len(set(labels)), list(labels)


def load_variant_module(path):
    path = Path(path).resolve()
    spec = importlib.util.spec_from_file_location("eval_variant", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if not hasattr(mod, "cluster"):
        raise SystemExit(f"{path} defines no cluster() function")
    return mod.cluster


class Overrides:
    """Temporarily patch whitelisted diarization module constants."""

    def __init__(self, pairs):
        self.pairs = dict(pairs)
        self.threshold = self.pairs.pop("THRESHOLD", None)
        self.saved = {}

    def __enter__(self):
        for k, v in self.pairs.items():
            self.saved[k] = getattr(diarization, k)
            setattr(diarization, k, v)
        return self

    def __exit__(self, *exc):
        for k, v in self.saved.items():
            setattr(diarization, k, v)
        return False


def parse_set(items):
    out = {}
    for item in items or []:
        if "=" not in item:
            raise SystemExit(f"--set expects KEY=VALUE, got {item!r}")
        k, v = item.split("=", 1)
        k = k.strip()
        if k not in TUNABLES:
            raise SystemExit(f"--set: unknown key {k!r}; allowed: {sorted(TUNABLES)}")
        out[k] = TUNABLES[k](v)
    return out


def evaluate(fixtures, cluster_fn, threshold, overrides=None):
    """Return {key: {...}} for one configuration, keyed by pseudonym."""
    results = {}
    ctx = Overrides(overrides or {})
    with ctx:
        thr = ctx.threshold if ctx.threshold is not None else threshold
        for fx in fixtures:
            auto, _ = run_cluster(fx, cluster_fn, None, thr)
            forced = None
            if fx["expected_speakers"]:
                forced, _ = run_cluster(fx, cluster_fn, fx["expected_speakers"], thr)
            results[fx["key"]] = {
                "auto": auto,
                "forced": forced,
                "threshold": thr,
                "windows": int(len(fx["windows"])),
            }
    return results


