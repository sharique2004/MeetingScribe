def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fixtures", default=str(FIXTURES),
                    help="real corpus directory (default test/fixtures)")
    ap.add_argument("--synthetic", default=str(SYNTHETIC),
                    help="synthetic corpus directory (default test/synthetic); "
                         "skipped with a note when absent")
    ap.add_argument("--no-synthetic", action="store_true",
                    help="real corpus only. The accuracy report then loses the only "
                         "constructed ground truth it has — say so if you quote it.")
    ap.add_argument("--threshold", type=float, default=DEFAULT_THRESHOLD)
    ap.add_argument("--set", dest="sets", action="append",
                    help="variant override, e.g. --set FOLD_MAX_FRAGMENTATION=0.15 "
                         "(repeatable; see TUNABLES)")
    ap.add_argument("--variant-module",
                    help="python file defining cluster(embeddings, n_speakers, threshold, durations)")
    ap.add_argument("--baseline", help="JSON snapshot to compare against (A side)")
    ap.add_argument("--save-baseline",
                    help="write this run's {pseudonym: result} map to JSON (refused during "
                         "an A/B run, which has no single result map — use --json)")
    ap.add_argument("--check", action="store_true",
                    help="gate: fail if any fixture's auto count differs from its "
                         "baseline entry, or has no baseline entry at all")
    ap.add_argument("--max-changed", type=int, default=0,
                    help="A/B gate: max meetings allowed to change (default 0)")
    ap.add_argument("--max-worse", type=int, default=0,
                    help="A/B gate: max meetings allowed to get worse (default 0)")
    ap.add_argument("--json", dest="json_out", help="also dump full results here")
    ap.add_argument("--show-titles", action="store_true",
                    help="print real fixture slugs instead of the pseudonyms. Local "
                         "use only — the slugs are meeting titles with participant "
                         "names in them, and this report gets pasted into docs.")
    args = ap.parse_args(argv)

    overrides = parse_set(args.sets)
    variant_fn = load_variant_module(args.variant_module) if args.variant_module else None

    # The real corpus is addressed ENTIRELY through the pseudonym -> directory
    # map in its own gitignored index: no table in this file knows a directory
    # name. No map, no real corpus — which is the normal state on a clean clone,
    # and is reported rather than raised.
    real_dir = Path(args.fixtures)
    label_map, why_not = load_label_map(real_dir)
    real_available = bool(label_map)
    fixtures = []
    if real_available:
        fixtures = load_fixtures(real_dir, corpus="real")
        if not fixtures:
            real_available = False
            why_not = ("%s holds no frozen fixtures (no analysis.npz + meeting.json "
                       "pair), so the\n      real corpus is unavailable." % real_dir)
    if not real_available:
        print("note: THE REAL CORPUS IS NOT LOADED.")
        print("      %s" % why_not)
        print("      Every accuracy number below therefore covers the synthetic "
              "corpus only,\n      and the real-corpus line is absent rather than "
              "zero.\n")
    else:
        unmapped = [fx["key"] for fx in fixtures if fx["key"] not in LABEL_KINDS]
        if unmapped:
            print("note: %d fixture(s) in %s are not in the index's label map, so they "
                  "carry no\n      pseudonym and no baseline entry. --check reports them "
                  "as UNCOVERED. Give\n      each one a label in %s/%s and a row in "
                  "LABEL_KINDS.\n"
                  % (len(unmapped), real_dir, real_dir, FIXTURE_INDEX))
    synth_dir = Path(args.synthetic)
    if args.no_synthetic:
        print("note: --no-synthetic — the constructed-truth corpus is NOT loaded, so the")
        print("      accuracy report below covers inferred truth only.\n")
    else:
        n_before = len(fixtures)
        fixtures += load_fixtures(synth_dir, corpus="synthetic", required=False)
        if len(fixtures) == n_before:
            print("note: no synthetic fixtures at %s — regenerate them with\n"
                  "      python tools/make_synthetic_fixtures.py . The accuracy report"
                  " below\n      therefore covers inferred truth only.\n" % synth_dir)
    # Report real fixtures first, in pseudonym order, so the table reads
    # A, B, C… then the synthetic rows. Unlabelled real fixtures sort first
    # ('?' < 'A'), which is where they should be: they need a label.
    fixtures.sort(key=lambda fx: (CORPUS_ORDER.index(fx.get("corpus", "real")),
                                  label_of(fx["key"]), fx["key"]))

    ab_mode = bool(overrides or variant_fn or args.baseline)

    # Evaluated before the header so ACCURACY — the number the header leads with
    # — is a measurement of this run, not of a previous one.
    base = evaluate(fixtures, diarization.cluster, args.threshold)

    print_header(fixtures, base, args.threshold, overrides, args.variant_module,
                 args.show_titles)

    exit_code = 0
    # The {key: result} map a baseline snapshot must contain. An A/B run has two
    # such maps and therefore no baseline to save — see the --save-baseline guard.
    by_key = base

    if not ab_mode:
        print("CURRENT CLUSTERING (no variant)\n")
        mismatches, uncovered = print_baseline_table(fixtures, base, args.show_titles)
        print()
        if not real_available:
            # The golden fixture is a real-corpus fixture. Claiming a pass here
            # would be claiming a check that never ran; failing would call a
            # clean clone broken. Say plainly that it did not run.
            print("golden regression: NOT RUN — %s lives in the real corpus, which is "
                  "not\n  loaded (see the note at the top). Nothing below has been "
                  "checked against it." % GOLDEN_KEY)
        else:
            fails = check_golden(fixtures, base)
            if fails:
                print("GOLDEN REGRESSION FAILURES:")
                for f in fails:
                    print("  !! " + f)
                exit_code = 1
            else:
                print("golden regression: OK (39 windows, 2 auto clusters, "
                      "{you,s1,s2}, 0 warnings)")
        if args.check:
            print()
            cov = coverage_summary(fixtures)
            if uncovered:
                print("BASELINE COVERAGE GAP — %d of %d fixtures have no baseline entry, "
                      "so --check\n  did NOT validate them:" % (len(uncovered), cov["n"]))
                for key in uncovered:
                    print("    - %s" % row_name(key, args.show_titles))
                print("  Add them to the current baseline generation (%s: GEN3_REAL or\n"
                      "  GEN3_SYNTHETIC, with today's measured count) and to LABEL_KINDS "
                      "before\n  trusting this gate.%s"
                      % (BASELINE_DATE,
                         "" if args.show_titles else
                         " Re-run with --show-titles to see which fixtures these are."))
                exit_code = 1
            if mismatches:
                print("BASELINE NOT REPRODUCED — %d discrepancies:" % len(mismatches))
                for key, want, got in mismatches:
                    print("  !! %s: %s says %d, harness says %d"
                          % (row_name(key, args.show_titles),
                             BASELINE_SOURCE.get(key, "baseline"), want, got))
                print("  Do NOT adjust the harness to match. A human must adjudicate.")
                print("  If the rule changed ON PURPOSE, read ACCURACY at the top first:"
                      " a re-baseline\n  is only defensible when accuracy did not get "
                      "worse. Then add a NEW dated\n  generation — do not edit %s in "
                      "place." % BASELINE_DATE)
                exit_code = 1
            if not uncovered and not mismatches:
                print("BASELINE REPRODUCED: all %d/%d fixtures match their %s entry.\n"
                      "  What this gate does and does not prove:"
                      % (len(cov["baselined"]), cov["n"], BASELINE_DATE))
                print("    proves : clustering behaviour is unchanged on all %d fixtures."
                      % cov["n"])
                print("    does NOT prove: that those counts are CORRECT. Correctness is"
                      " the ACCURACY\n                    block at the top of this report,"
                      " measured against TRUTH:")
                for corpus in CORPUS_ORDER:
                    sub = of_corpus(fixtures, corpus)
                    if not sub:
                        continue
                    a = accuracy_of(sub, base)
                    print("                      %-10s %d of %d truth-backed correct, "
                          "%d with no truth (never scored)"
                          % (corpus, len(a["hits"]), len(a["scorable"]),
                             len(a["unscored"])))
            wrong = pinned_but_wrong(fixtures)
            print()
            if wrong:
                print("PINNED BUT WRONG — %d baseline entr%s a number TRUTH "
                      "contradicts."
                      % (len(wrong),
                         "y holds" if len(wrong) == 1 else "ies hold"))
                print("  These are pinned so drift is still caught, NOT endorsed:")
                for key, b, t in wrong:
                    print("    - %-40s baseline %d, truth %d  (%s)"
                          % (row_name(key, args.show_titles), b, t,
                             truth_of(key)[1]))
                print("  The gate passing does not make these right. Fixing them is a "
                      "clustering change,\n  not a baseline edit.")
            else:
                print("PINNED BUT WRONG: none — every baselined fixture that has truth "
                      "is pinned at\n  the true count. Fixtures with no truth are pinned "
                      "with no accuracy claim.")
    else:
        if args.baseline:
            snap = json.loads(Path(args.baseline).read_text(encoding="utf-8"))
            a_side = snap.get("results") or {}
            if snap.get("shape") == "ab" or set(a_side) == {"A", "B"}:
                raise SystemExit(
                    "%s is an A/B dump ({\"A\":…,\"B\":…}), not a {key: result} "
                    "baseline. Re-record it with a plain (non-variant) run:\n"
                    "  python tools/eval_diarization.py --save-baseline %s"
                    % (args.baseline, args.baseline)
                )
            missing = [f["key"] for f in fixtures if f["key"] not in a_side]
            if missing:
                print("baseline snapshot is missing %d fixtures: %s"
                      % (len(missing), ", ".join(row_name(k, args.show_titles).strip()
                                                 for k in missing)))
                exit_code = 1
                fixtures = [f for f in fixtures if f["key"] in a_side]
        else:
            a_side = base
        fn = variant_fn or diarization.cluster
        b_side = evaluate(fixtures, fn, args.threshold, overrides)
        print("A/B: A = current clustering%s, B = variant\n"
              % (" (from %s)" % args.baseline if args.baseline else ""))
        changed, better, worse = print_ab_table(fixtures, a_side, b_side,
                                                args.show_titles)
        gfails = check_golden(fixtures, b_side) if real_available else []
        print()
        if not real_available:
            print("golden regression: NOT RUN under the variant — the real corpus, "
                  "which holds\n  the golden fixture, is not loaded.")
        if gfails:
            print("GOLDEN REGRESSION FAILURES under variant:")
            for f in gfails:
                print("  !! " + f)
            exit_code = 1
        if len(changed) > args.max_changed:
            print("GATE FAILED: %d meetings changed (--max-changed %d)"
                  % (len(changed), args.max_changed))
            exit_code = 1
        if len(worse) > args.max_worse:
            print("GATE FAILED: %d meetings got worse (--max-worse %d)"
                  % (len(worse), args.max_worse))
            exit_code = 1
        if exit_code == 0:
            print("GATE PASSED")
        by_key = None  # an A/B run has two result maps, so no baseline to save

    payload = {
        "shape": "ab" if ab_mode else "by_key",
        "threshold": args.threshold,
        "overrides": overrides,
        "variant_module": args.variant_module,
        "results": {"A": a_side, "B": b_side} if ab_mode else by_key,
    }
    if args.save_baseline:
        if by_key is None:
            # Refused, not silently mangled: writing {"A":…,"B":…} under
            # "results" produced a file --baseline/--check could not read.
            print("\n!! REFUSING to write %s: --save-baseline needs one {key: result} "
                  "map, and this\n   was an A/B run (variant --set / --variant-module / "
                  "--baseline) which has two.\n   Record the baseline from a plain run "
                  "first, then A/B against it:\n     python tools/eval_diarization.py "
                  "--save-baseline %s\n   To keep this run's numbers, use --json "
                  "(dumped as shape=\"ab\", not loadable as a baseline)."
                  % (args.save_baseline, args.save_baseline))
            exit_code = 1
        else:
            Path(args.save_baseline).write_text(
                json.dumps(payload, indent=1), encoding="utf-8")
            print("\nbaseline written to %s (%d fixtures)"
                  % (args.save_baseline, len(by_key)))
    if args.json_out:
        Path(args.json_out).write_text(json.dumps(payload, indent=1), encoding="utf-8")

    print("\nexit %d" % exit_code)
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
