def short(slug, width=46):
    return slug if len(slug) <= width else slug[: width - 1] + "…"


def row_name(key, show_titles):
    """What identifies a fixture in the report.

    Pseudonym by default: the report is the thing people paste into design docs,
    and the real slugs are meeting titles with participant names in them. Under
    --show-titles the slug is looked up in the gitignored index — which is the
    only place in this process where it exists at all.
    """
    if show_titles:
        return short(SLUG_BY_LABEL.get(key, key))
    return "%-7s %s" % (label_of(key), kind_of(key))


def blind_spots(fixtures):
    """Statement (a) recomputed from the fixtures actually loaded.

    Hardcoding these numbers is how the previous version came to print "11 of 12
    caches" over a corpus of 22 that by then included mic-track fixtures. Every
    quantity below is counted from `fixtures`; only the shape of the sentence is
    fixed. (b) is a property of the method, not of the corpus, so it is constant.
    """
    n = len(fixtures)
    sys_only = [f for f in fixtures if f["cached_tracks"] == ["system"]]
    mic_only = [f for f in fixtures if f["cached_tracks"] == ["mic"]]
    both = [f for f in fixtures if len(f["cached_tracks"]) > 1]
    online_no_mic = [f for f in sys_only if f["mode"] == "online"]
    lines = [
        "(a) of %d caches: %d system-only, %d mic-only, %d hold both tracks."
        % (n, len(sys_only), len(mic_only), len(both)),
        "    %d online meeting(s) cache the system track with NO mic embeddings, so"
        % len(online_no_mic),
        "    \"You vs remote\" separation cannot be A/B tested from cache."
        + ("" if both else "\n    No fixture at all exercises the two-track path."),
        "    The %d mic-only cache(s) are in-person meetings: their clusters INCLUDE the"
        % len(mic_only),
        "    local user, so a count there is not comparable to a system-track count.",
        "(b) Cache-based A/B cannot cover changes to window geometry, VAD gating, or",
        "    window-length rules — any such change invalidates all caches.",
    ]
    return "\n".join(lines)


def coverage_summary(fixtures):
    """Honest accounting of what --check actually validates. Returns a dict."""
    keys = [fx["key"] for fx in fixtures]
    tiers = {t: 0 for t in TIER_ORDER}
    for k in keys:
        tiers[truth_of(k)[1]] += 1
    return {
        "n": len(keys),
        "baselined": [k for k in keys if k in BASELINE],
        "uncovered": [k for k in keys if k not in BASELINE],
        "tiers": tiers,
        "stale_baselines": [k for k in BASELINE if k not in keys],
    }


